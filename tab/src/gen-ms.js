// how many stock calls (getRef #37; getRef #85) in a #43 body text are NOT behind a PlayerSigningEval null guard (getRef #37; pushNull; ne; jf, or
// eq; jt, directly or through a local as Preseason Weeks' handler does: storeRec x; localRec x; pushNull; ne; jf, within the lines before).
// 0 = safe for requests without PlayerSigningEval. Works on spexasm sources and on disassembly (.tok 9 2 0 0 / %n locals).
function unguardedStockCalls(text) {
  const t = text.split(/\r?\n/).map((l) => l.replace(/;.*$/, '').trim()).filter((l) => l && !l.startsWith('.local') && !/^\.(target|mode|self)/.test(l));
  let bad = 0;
  for (let k = 1; k < t.length; k++) {
    if (!(t[k - 1] === 'getRef #37' && t[k] === 'getRef #85')) continue;
    const w = t.slice(Math.max(0, k - 10), k - 1).join('|');
    if (!/getRef #37\|(storeRec (\S+)\|localRec \2\|)?pushNull\|(ne\|jf|eq\|jt) @\w+/.test(w)) bad++;
  }
  return bad;
}

// how a mod reads its own row (what the manifest spec shows): sets int <out> to the row's value, or to <dflt> when the record is missing
function readSnippet(T, mod, row, out = 'msV', fuLocal = 'fu') {
  const r = T.bandRows.find((x) => x.mod === mod && x.id === row); if (!r) throw new Error(`${mod}/${row} is not a band row`);
  const lo = T.band.base + r.slot.record * T.band.recordSize, hi = lo + T.band.recordSize - 1;
  return [`; ---- Mod Settings: ${mod}/${row} -> int ${out} (record ${r.slot.record}, bits ${r.slot.bit}..${r.slot.bit + r.slot.width - 1}; ${r.default} when not set yet)`,
    `; needs: .local record:CrossArcData[] msA / .local record:CrossArcData msC / .local int msI / .local int msN / .local int ${out}`,
    `  push ${r.default}`, `  storeInt ${out}`, `  localRec ${fuLocal}`, '  pushNull', '  eq', '  jt @msRd',
    `  localRec ${fuLocal}`, '  getRef CrossArcDataArray', '  storeRec msA', '  localRec msA', '  pushNull', '  eq', '  jt @msRd',
    '  localRec msA', '  getRef Count', '  localRec msA', '  push 0', '  call', '  storeInt msN', '  push 0', '  storeInt msI',
    '@msRs:', '  localInt msI', '  localInt msN', '  lt', '  jf @msRd',
    '  localRec msA', '  localInt msI', '  getDynRef', '  storeRec msC', '  localRec msC', '  pushNull', '  eq', '  jt @msRn',
    '  localRec msC', '  getInt Value', `  push ${lo}`, '  ge', '  jf @msRn', '  localRec msC', '  getInt Value', `  push ${hi}`, '  le', '  jf @msRn',
    '  localRec msC', '  getInt Value', `  push ${lo}`, '  sub', `  push ${pow2(r.slot.bit)}`, '  div', `  push ${pow2(r.slot.width)}`, '  mod', `  storeInt ${out}`, '  jmp @msRd',
    '@msRn:', '  localInt msI', '  push 1', '  add', '  storeInt msI', '  jmp @msRs',
    '@msRd:', '; ---- end of the Mod Settings read'];
}

function generate(outDir, T, { host = 46, h43 = 'replace' } = {}) {
  fs.mkdirSync(outDir, { recursive: true });
  const files = [];
  if (!T.bandRows.length) return { files, report: ['no band rows: no expression code'] };
  const iss = path.join(outDir, 'ms-issue.spexasm'), h43f = path.join(outDir, 'ms-h43.spexasm');
  fs.writeFileSync(iss, issueSource(T, host)); fs.writeFileSync(h43f, h43Source(T, { h43 }));
  files.push(iss, h43f);
  return { files, report: [`ms-issue.spexasm -> ${HOSTS[host]} (append): records ${T.records.join(',')}, ${T.bandRows.length} band rows`, `ms-h43.spexasm -> none()#43 (${h43})`] };
}
