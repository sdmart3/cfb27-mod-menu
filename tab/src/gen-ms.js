#!/usr/bin/env node
// gen-ms.js: the Mod Settings expression broker (docs/design.md, Built section). Two generated sources:
//   ms-issue.spexasm   APPEND to a host body (default bool() CareerFlow_UpdateCareerHubInfoReaction = #46, stock body 0 locals; NOT #29, which is at
//                      254 of 256 locals on the Playoff Customizer family patches). It
//                        1. finds user 0's band records (one per used record) and adds a missing one with the rows' defaults (grow-and-swap, only while the
//                           record table holds fewer than ADD_CAP rows);
//                        2. walks the open request list ONCE and notes which band rows already have a broker request (marker = CpuResponseMinDuration);
//                        3. issues one hidden request for each band row that has none: LostPracticeSquadPlayerRequest, Notification style, TypeName =
//                           Description = Title = the stock WeeklyTip title "Legacy Leaderboard" (NFLSeason wk 15), 8 response forms (a count no other
//                           hidden-request row uses), Priority = the row's prio + its current value (what the page reads), the current form selected.
//                      The request recipe is Dynasty Extensions' issuePart (gen-de.js; Preseason Weeks' chooser issue, proven in game) with the marker, the
//                      TypeName and the form count changed. Idempotent: a host that runs many times per week issues nothing once every row has its request.
//   ms-h43.spexasm     none()#43 REPLACE (default; APPEND only on a base whose handler guards the stock call, see h43Source)
//                      (LostPracticeSquadPlayerRequest.HandleResponse): for a request whose marker is in the broker range, the marker
//                      itself says where the value goes (marker = MARKER_BASE + prio * 512 + record * 64 + bit * 4 + (width - 1)): the answer sets
//                      Priority = prio + value, RequestForm / DefaultResponse, Refresh (the DE lab finding: the UI reads Priority only after a Refresh),
//                      and writes the value into the record's bits in place. No per-row code in the handler.
// A mod reads its row with readSnippet() (the record scan + 2 lines of int math), see docs/manifest-spec.md.
//
// usage: node modsettings/src/gen-ms.js <out dir> [manifest.json ...] [--host 46|29|283] [--h43 replace|append]
